async function request(method, endpoint, body, bearer, expected = 201) {
  const res = await fetch(base + endpoint, {method, headers:{'Content-Type':'application/json',...(bearer? {Authorization:`Bearer ${bearer}`}:{})}, ...(body === undefined ? {} : {body:JSON.stringify(body)})});
  const json = await res.json(); evidence.push({method,endpoint,status:res.status,body: endpoint === '/alerts' || endpoint === '/alerts/' ? json : undefined});
  assert.equal(res.status,expected,`${endpoint}: ${JSON.stringify(json)}`);return json;
}
